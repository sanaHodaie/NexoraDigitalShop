"""Generate bundled, content-addressed catalogue previews. Run with backend's Pillow environment.

python scripts/build-admin-thumbnails.py [--check]
Original storefront images and live product records are never changed.
"""
import argparse
import hashlib
import json
from io import BytesIO
from pathlib import Path

from PIL import Image, ImageOps

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / 'public/assets/admin/catalogue'
REGISTRY = ROOT / 'AdminPanel/src/catalogueImages.js'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    sources = set()
    for name in ('products.json', 'catalog-products.json'):
        sources.update(p['image'] for p in json.loads((ROOT / 'backend/data' / name).read_text()))
    assets = {}
    entries, optimized = [], []
    original_bytes = 0
    for source in sorted(sources):
        path = ROOT / 'public' / source.lstrip('/')
        if path.suffix.lower() not in {'.jpg', '.jpeg', '.png', '.webp'}:
            continue
        raw = path.read_bytes()
        original_bytes += len(raw)
        with Image.open(BytesIO(raw)) as im:
            im = ImageOps.exif_transpose(im).convert('RGBA')
            im.thumbnail((320, 320), Image.Resampling.LANCZOS)
            output = BytesIO()
            im.save(output, 'WEBP', quality=76, method=6)
        thumbnail = output.getvalue()
        filename = hashlib.sha256(thumbnail).hexdigest()[:24] + '.webp'
        assets[filename] = thumbnail
        entries.append(f'  {json.dumps(source)}: {json.dumps("/assets/admin/catalogue/" + filename)},')
        webp = path.with_suffix('.webp')
        if webp != path and webp.exists():
            optimized.append(f'  {json.dumps(source)}: {json.dumps("/" + webp.relative_to(ROOT / "public").as_posix())},')
    registry = ('// Generated by scripts/build-admin-thumbnails.py; do not hand-edit.\n'
                'export const catalogueImages = {\n' + '\n'.join(entries) + '\n};\n'
                'export const optimizedSources = {\n' + '\n'.join(optimized) + '\n};\n')
    if args.check:
        assert REGISTRY.read_text() == registry, 'Catalogue registry is stale; regenerate thumbnails.'
        assert {p.name for p in ASSETS.glob('*.webp')} == set(assets), 'Thumbnail file set is stale.'
        for filename, raw in assets.items():
            assert (ASSETS / filename).read_bytes() == raw, 'Thumbnail differs: ' + filename
    else:
        ASSETS.mkdir(parents=True, exist_ok=True)
        for filename, raw in assets.items():
            (ASSETS / filename).write_bytes(raw)
        for path in ASSETS.glob('*.webp'):
            if path.name not in assets:
                path.unlink()
        REGISTRY.write_text(registry)
    saved = 100 * (1 - sum(map(len, assets.values())) / original_bytes)
    print(f'{len(entries)} source paths, {len(assets)} bundled previews; '
          f'{original_bytes // 1024} KiB original -> {sum(map(len, assets.values())) // 1024} KiB previews ({saved:.1f}% smaller).')


if __name__ == '__main__':
    main()
