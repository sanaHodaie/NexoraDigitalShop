"""Build content-addressed responsive photos from bundled public artwork (Pillow pinned in backend).

Run: backend/.venv/bin/python scripts/build-store-images.py [--check]
Originals, product records, custom URLs and alpha channels are preserved.
"""
import argparse
import hashlib
import json
from io import BytesIO
from pathlib import Path

from PIL import Image, ImageOps

ROOT = Path(__file__).resolve().parents[1]
DEST = ROOT / 'public/assets/store-images'
REGISTRY = ROOT / 'src/data/responsive-images.js'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    sources = sorted((ROOT/'public/assets/products').glob('*.webp'))
    sources += sorted((ROOT/'public/assets').glob('*.webp'))
    sources += sorted((ROOT/'public/assets/category-heroes').glob('*.webp'))
    output, mapping = {}, {}
    original_total, card_total = 0, 0
    for path in sources:
        raw = path.read_bytes()
        with Image.open(BytesIO(raw)) as opened:
            image = ImageOps.exif_transpose(opened).convert('RGBA')
            variants = []
            for width in sorted({min(target, image.width) for target in (320, 640, 960)}):
                resized = image.copy()
                resized.thumbnail((width, 10000), Image.Resampling.LANCZOS)
                buf = BytesIO()
                resized.save(buf, 'WEBP', quality=80, method=6)
                data = buf.getvalue()
                filename = hashlib.sha256(data).hexdigest()[:24]+'.webp'
                output[filename] = data
                variants.append([width, '/assets/store-images/'+filename])
            mapping['/'+path.relative_to(ROOT/'public').as_posix()] = variants
            original_total += len(raw)
            card_total += len(output[Path(variants[0][1]).name])
    content = '// Generated by scripts/build-store-images.py with backend Pillow. Originals are retained.\n'
    content += 'export const responsiveImages = '+json.dumps(mapping, ensure_ascii=False, separators=(',', ':'))+';\n'
    if args.check:
        assert REGISTRY.read_text() == content, 'Responsive registry is stale'
        assert {p.name for p in DEST.glob('*.webp')} == set(output), 'Responsive asset set is stale'
        for name, raw in output.items():
            assert (DEST/name).read_bytes() == raw, 'Responsive asset differs: '+name
    else:
        DEST.mkdir(exist_ok=True, parents=True)
        for name, raw in output.items():
            (DEST/name).write_bytes(raw)
        for path in DEST.glob('*.webp'):
            if path.name not in output:
                path.unlink()
        REGISTRY.write_text(content)
    print(f'{len(mapping)} sources; {len(output)} responsive assets; '
          f'{original_total//1024} KiB originals -> {card_total//1024} KiB 320px variants '
          f'({100*(1-card_total/original_total):.1f}% smaller).')


if __name__ == '__main__':
    main()
