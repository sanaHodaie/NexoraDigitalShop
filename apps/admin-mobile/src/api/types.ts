export type Manager = { id: number; email: string; name: string; permissions: string[] };
export type Page<T> = { items: T[]; total: number; page: number; pageSize?: number; size?: number };
export type RequestStatus = 'new' | 'reviewing' | 'contacted' | 'quoted' | 'closed' | 'cancelled' | 'approved';
export type CustomerRequest = {
  id: number; kind: 'wholesale' | 'support'; status: RequestStatus;
  createdAt: string; updatedAt: string; version: number;
  telegramUserId: string; telegramUsername: string; staffNote: string;
  details: { name: string; phone: string; company: string; items: string; quantity: number;
    city: string; address: string; notes: string };
  trackingCode: string | null; hasInvoice: boolean;
  deliveryStatus?: 'none' | 'pending' | 'sent' | 'failed';
  invoice: null | { totalRial: string; shippingRial: string; terms: string;
    lines: { name: string; quantity: number; unitPriceRial: string; totalRial: string }[] };
};
export type RequestStats = { total: number; statuses: Partial<Record<RequestStatus, number>>;
  daily: { day: string; requests: number }[] };
export type Dashboard = { products: number; users: number; orders: number; revenue: number;
  lowStock: number; subscribers: number; statuses: Record<string, number>;
  daily: { date: string; value: number }[] };
export type Product = { id: string; name: string; nameEn: string; category: string;
  price: number; stock: number; isActive: boolean; image: string; categoryFa?: string;
  brand?: string; description?: string; specs?: string[]; badge?: string; kindLabel?: string };
export type Order = { id: number; email: string; name: string; total: number; status: string;
  createdAt: string; lines: { name: string; quantity: number; unitPrice: number }[] };
export type Audit = { id: number; event: string; createdAt: string; userId: number | null;
  subjectId: string | null; email?: string; fullName?: string | null };
